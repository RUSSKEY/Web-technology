// Функция принимает число n и возвращает n-е число Фибоначчи.
// Я использую цикл, а не рекурсию, чтобы избежать переполнения стека при больших n.
// Так как числа Фибоначчи растут очень быстро, и n может быть до 1000,
// я использую тип BigInt (буквы n в конце чисел), чтобы не потерять точность.

function fibb(n) {
  // Для n = 0 и n = 1 возвращаем сами числа.
  if (n === 0) return 0n;
  if (n === 1) return 1n;

  // Переменные для хранения двух предыдущих чисел Фибоначчи.
  let prev = 0n; 
  let curr = 1n; 
  let next = 0n;

  // Цикл начинается с 2, так как первые два числа мы уже задали.
  for (let i = 2; i <= n; i++) {
    next = prev + curr; // Следующее число = сумма двух предыдущих
    prev = curr;        // Сдвигаем "окно": старое curr становится prev
    curr = next;        // Новое next становится curr
  }

  // Возвращаем результат.
  return curr;
}