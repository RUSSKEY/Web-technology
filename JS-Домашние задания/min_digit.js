//Я использую цикл while, чтобы перебрать каждую цифру числа. 
// Внутри цикла я беру остаток от деления на 10 (% 10), чтобы получить последнюю цифру, и сравниваю её с текущим минимумом.
//  Затем я уменьшаю число, вычитая эту цифру и деля на 10. 
// Встроенные функции не использую, только базовую математику
function minDigit(x) {
  // Если число равно 0, то минимальная цифра — это 0
  if (x === 0) {
    return 0;
  }

  let min = 9; // Начинаем с максимально возможной цифры

  while (x > 0) {
    let digit = x % 10; // Получаем последнюю цифру числа
    
    if (digit < min) {
      min = digit; // Если цифра меньше текущей минимальной, запоминаем её
    }
    
    // Убираем последнюю цифру из числа
    // Например, если было 123, станет 12.3, отбрасываем дробную часть
    x = (x - digit) / 10; 
  }

  return min;
}
