// Функция принимает число n (количество найденных записей) и возвращает строку.
// Задача: правильно просклонять слово "запись" в зависимости от числа.
// Логика русского языка:
// - Если число оканчивается на 1 (но не 11) -> "запись" (например, 1, 21, 31).
// - Если оканчивается на 2, 3, 4 (но не 12, 13, 14) -> "записи" (например, 2, 23).
// - Во всех остальных случаях -> "записей" (0, 5, 11, 100).
// Для этого я беру остаток от деления на 10 и на 100.

function pluralizeRecords(n) {
  // Берем последнюю цифру числа (например, для 23 это будет 3)
  let lastDigit = n % 10;
  
  // Берем две последние цифры (для 23 это 23, для 111 это 11)
  // Это нужно, чтобы правильно обработать исключения (11, 12, 13, 14)
  let lastTwoDigits = n % 100;

  let word;

  // Исключения: 11-14 всегда требуют слова "записей"
  if (lastTwoDigits >= 11 && lastTwoDigits <= 14) {
    word = "записей";
  } 
  // Если оканчивается на 1 (но не 11) — "запись"
  else if (lastDigit === 1) {
    word = "запись";
  } 
  // Если оканчивается на 2, 3 или 4 (но не 12, 13, 14) — "записи"
  else if (lastDigit >= 2 && lastDigit <= 4) {
    word = "записи";
  } 
  // Все остальные случаи (0, 5, 6, 7, 8, 9) — "записей"
  else {
    word = "записей";
  }

  // Возвращаем готовую строку с подставленным числом и словом
  return "В результате выполнения запроса было найдено " + n + " " + word;
}